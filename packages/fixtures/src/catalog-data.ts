type ConnOpts = Partial<Omit<Connection, 'id' | 'fromItemId' | 'target' | 'kind'>>;
const required = (from: string, to: Target, o: ConnOpts = {}): Connection => ({
  id: cid(),
  fromItemId: from,
  target: to,
  kind: 'required',
  rule: 'per_piece',
  qty: 1,
  ...o,
});
const check = (from: string, to: Target, o: ConnOpts = {}): Connection => ({
  id: cid(),
  fromItemId: from,
  target: to,
  kind: 'check',
  rule: 'per_piece',
  qty: 1,
  ...o,
});
const recommended = (from: string, to: Target, o: ConnOpts = {}): Connection => ({
  id: cid(),
  fromItemId: from,
  target: to,
  kind: 'recommended',
  rule: 'once_per_order',
  qty: 1,
  ...o,
});

